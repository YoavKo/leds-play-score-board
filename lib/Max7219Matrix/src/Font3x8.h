#pragma once
#include <stdint.h>

// 7-segment style 3x8 digits '0'..'9': 3 columns per glyph, one byte per
// column, bit 0 = top row.
namespace max7219 {

static const uint8_t kFont3x8Digits[] = {
    0xFF, 0x81, 0xFF,  // '0'
    0x00, 0x00, 0xFF,  // '1'
    0xF9, 0x89, 0x8F,  // '2'
    0x89, 0x89, 0xFF,  // '3'
    0x0F, 0x08, 0xFF,  // '4'
    0x8F, 0x89, 0xF9,  // '5'
    0xFF, 0x89, 0xF9,  // '6'
    0x01, 0x01, 0xFF,  // '7'
    0xFF, 0x89, 0xFF,  // '8'
    0x8F, 0x89, 0xFF,  // '9'
};

}  // namespace max7219
